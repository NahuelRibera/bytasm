import { expect, test } from "@playwright/test";
import { FIXTURES_URL } from "../playwright.config";
import { createProject, expectNoAxeViolations, FIXTURE, importFile } from "./helpers";

test("fixture → understandable observations → exact evidence → scoped strings → snapshot", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 740 });
  await createProject(page, FIXTURES_URL, "Evidence-led review");
  await importFile(page, FIXTURE("hello_v1-aarch64.elf"), { sample: "review", label: "v1", filename: "a".repeat(240) + ".elf" });
  await expect(page.getByRole("heading", { name: "Section sizes and entropy measurements" })).toBeVisible();
  await expect(page.getByRole("img", { name: /declared raw section bytes/ }).first()).toBeVisible();
  await expectNoAxeViolations(page);
  await page.getByRole("button", { name: "Run pattern matching…" }).click();
  await page.getByRole("button", { name: "Start run", exact: true }).click();
  await expect(page.getByTestId("status").first()).toHaveText("Succeeded");
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0);
  const guide = page.getByRole("region", { name: "Evidence-led explanations" });
  const url = guide.locator("article").filter({ has: page.getByRole("heading", { name: "url_reference", exact: true }) });
  await expect(url.getByText(/does not prove a network request/)).toBeVisible();
  await url.getByRole("link", { name: "Inspect exact finding and evidence" }).click();
  await expect(page.getByRole("region", { name: "Evidence: url_reference", exact: true })).toBeVisible();
  await page.getByRole("link", { name: /Search the strings/ }).click();
  await expect(page.getByRole("tab", { name: /Strings/ })).toHaveAttribute("aria-selected", "true");
  expect(new URL(page.url()).searchParams.get("run_id")).toMatch(/^[0-9a-f]{32}$/);
  await page.getByLabel("Heuristic category", { exact: true }).selectOption("path_like");
  await expect(page.getByText(/Path-like text hidden/).first()).toBeVisible();
  await page.getByLabel("Sort / group", { exact: true }).selectOption("category");
  await page.getByRole("checkbox", { name: /Show path-like values/ }).check();
  await expectNoAxeViolations(page);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0);
  await page.getByRole("link", { name: /Section \d+:/ }).first().click();
  await expect(page.getByRole("region", { name: "Sections table", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Preview new report" }).click();
  await expect(page.getByRole("heading", { name: "Report preview", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Evidence-led explanations" })).toBeVisible();
  const href = await page.getByRole("link", { name: "Download standalone HTML" }).getAttribute("href");
  const html = await (await page.request.get(new URL(href!, page.url()).href)).text();
  expect(html).toContain("Why these observations appear");
  expect(html).toContain("does not prove a network request");
  expect(html).not.toContain("<script");
  await expectNoAxeViolations(page);
});
