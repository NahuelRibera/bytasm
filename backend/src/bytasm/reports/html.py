from typing import Any

from jinja2 import Environment

CSP = "default-src 'none'; style-src 'unsafe-inline'; img-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"
TEMPLATE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="{{ csp }}"><title>Bytasm static analysis report</title>
<style>body{font:16px system-ui,sans-serif;line-height:1.55;max-width:76rem;margin:auto;padding:1.5rem;color:#18212d;background:white}h1,h2,h3{line-height:1.25}section{border-top:1px solid #bac4d2;margin:1.5rem 0;padding-top:1rem}dt{font-weight:600}dd{margin:0 0 1rem 1rem}dd,p,li{overflow-wrap:anywhere}ul,ol{padding-left:1.5rem}.notice{border-left:4px solid #465b7a;padding:1rem;background:#f3f5f8}@media print{body{font-size:10pt;padding:0}section{break-inside:auto}h2,h3{break-after:avoid}}</style></head><body>
<h1>Bytasm static analysis report</h1><p>Schema {{ report.schema_version }} · scope: {{ report.scope.kind if report.scope else 'sample_version' }}</p>
<section class="notice"><h2>Analysis in plain language</h2>{% for paragraph in summary %}<p>{{ paragraph }}</p>{% endfor %}</section>
<p class="notice">This report may include file-derived text, changed strings and analyst-authored statements. Review it before sharing. Nothing was executed.</p>
{% macro value(item) %}{% if item is mapping %}<dl>{% for key, child in item.items() %}<dt>{{ key }}</dt><dd>{{ value(child) }}</dd>{% endfor %}</dl>{% elif item is sequence and item is not string %}<ol>{% for child in item %}<li>{{ value(child) }}</li>{% endfor %}</ol>{% elif item is none %}Not available{% else %}{{ item }}{% endif %}{% endmacro %}
{% for key, item in report.items() %}<section><h2>{{ key }}</h2>{{ value(item) }}</section>{% endfor %}
<footer>Generated by Bytasm. capa is a FLARE/Mandiant tool; packaged capa rules are licensed under Apache-2.0. Tool matches are observations requiring interpretation.</footer></body></html>"""


def render(document: dict[str, Any]) -> bytes:
    from bytasm.plain_summary import report_summary

    env = Environment(autoescape=True)
    return (
        env.from_string(TEMPLATE)
        .render(report=document, summary=report_summary(document), csp=CSP)
        .encode("utf-8")
    )
