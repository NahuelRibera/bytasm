def render(document: dict[str, Any]) -> bytes:
    from bytasm.review import report_review

    env = Environment(autoescape=True)
    return (
        env.from_string(TEMPLATE)
        .render(
            report=document,
            summary=document.get("summary", []),
            review=report_review(document),
            csp=CSP,
        )
        .encode("utf-8")
    )
