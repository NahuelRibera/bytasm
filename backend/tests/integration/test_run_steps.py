def test_cancel_after_the_last_step_committed_still_ends_cancelled(
    client: TestClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Cancel wins over the final status; every finished step keeps its results."""
    version_id = imported_version(client, ELF_X86_64)
    run_id = start_run(client, version_id)["id"]
    ctx = ctx_of(client)
    real_record = pipeline._record

    def record_then_cancel(deps: Any, rid: str, index: int, *rest: Any) -> str:
        status = real_record(deps, rid, index, *rest)
        if index == 1:
            with ctx.sessions() as session:
                runs.request_cancel(session, run_id)
        return status

    monkeypatch.setattr(pipeline, "_record", record_then_cancel)
    assert process(ctx) == "cancelled"
    run = run_of(client, run_id)
    assert [s["status"] for s in run["steps"]] == ["succeeded", "succeeded"]
    assert run["counts"]["findings"] == 2


def test_a_step_result_is_not_stored_once_cancel_was_requested(client: TestClient) -> None:
    version_id = imported_version(client, ELF_X86_64)
    run_id = start_run(client, version_id)["id"]
    with ctx_of(client).sessions() as session:
        assert runs.transition(session, run_id, "queued", "running")
        session.commit()
        assert runs.claim_step_commit(session, run_id)
        session.rollback()
        assert runs.request_cancel(session, run_id) == "requested"
        assert not runs.claim_step_commit(session, run_id)
        assert runs.still_running(session, run_id)
        session.rollback()
        # A finished run accepts neither.
        assert runs.transition(session, run_id, "running", "cancelled")
        session.commit()
        assert not runs.still_running(session, run_id)


def test_timeout_and_cancel_racing_record_one_outcome(tmp_path: Path) -> None:
    limits = ParserLimits(timeout_seconds=1.0, kill_grace_seconds=0.2)
    with api_client(make_settings(tmp_path, limits=limits)) as client:
        version_id = imported_version(client, ELF_X86_64)
        run_id = start_run(client, version_id)["id"]
        ctx = ctx_of(client)

        async def scenario() -> str | None:
            worker = Worker(
                deps_for(ctx, strings_command=fake_strings("hang")),
                ctx.settings.data_dir,
                asyncio.Event(),
            )
            task = asyncio.create_task(worker.process_next())
            await asyncio.sleep(0.95)  # cancel lands next to the 1 s deadline
            await asyncio.to_thread(client.post, f"/api/v1/runs/{run_id}/cancel")
            return await task

        status = asyncio.run(scenario())
        run = run_of(client, run_id)
        assert status == run["status"] == "cancelled"
        assert step_of(run, "strings")["status"] in ("timed_out", "cancelled")
        with ctx.sessions() as session:
            count = len(
                session.scalars(
                    select(ToolInvocation).where(
                        ToolInvocation.run_id == run_id, ToolInvocation.step_index == 0
                    )
                ).all()
            )
        assert count == 1
        assert list(ctx.tmp_dir.iterdir()) == []


# --- worker restart -------------------------------------------------------------


def _interrupted_run(client: TestClient, steps_done: int, cancel: bool = False) -> str:
    """A run left `running` with its first `steps_done` steps committed."""
    version_id = imported_version(client, ELF_X86_64, name=f"s{steps_done}{cancel}")
    run_id: str = start_run(client, version_id)["id"]
    with ctx_of(client).sessions() as session:
        assert runs.transition(session, run_id, "queued", "running", started_at=utcnow())
        for index, tool in list(enumerate(["strings", "yara-x"]))[:steps_done]:
            session.add(
                ToolInvocation(
                    run_id=run_id,
                    step_index=index,
                    tool_name=tool,
                    tool_version="x",
                    adapter_name="x",
                    adapter_version="x",
                    args={},
                    status="succeeded",
                    duration_ms=1,
                    warnings=[],
                )
            )
        if cancel:
            session.execute(
                update(AnalysisRun).where(AnalysisRun.id == run_id).values(cancel_requested=True)
            )
        session.commit()
    return run_id


@pytest.mark.parametrize(
    ("steps_done", "cancel", "status", "reason"),
    [
        (0, False, "failed", "worker_interrupted"),
        (1, False, "partial", "worker_interrupted"),
        (2, False, "succeeded", None),
        (1, True, "cancelled", None),
    ],
)
def test_worker_restart_never_leaves_a_run_running(
    client: TestClient, steps_done: int, cancel: bool, status: str, reason: str | None
) -> None:
    run_id = _interrupted_run(client, steps_done, cancel)
    with ctx_of(client).sessions() as session:
        assert runs.fail_interrupted_runs(session) == 1
    run = run_of(client, run_id)
    assert (run["status"], run["failure_reason"]) == (status, reason)
    expected = ["succeeded"] * steps_done + ["skipped"] * (2 - steps_done)
    assert [s["status"] for s in run["steps"]] == expected


