def test_admission_failing_between_steps_keeps_the_earlier_step(
    client: TestClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The blob is re-verified before every step; a change after step 1 stops step 2."""
    version_id = imported_version(client, ELF_X86_64)
    run_id = start_run(client, version_id)["id"]
    ctx = ctx_of(client)
    sha = client.get(f"/api/v1/sample-versions/{version_id}").json()["sha256"]
    real_record = pipeline._record

    def record_then_damage(*args: Any) -> str:
        status = real_record(*args)
        path = ctx.blobs.path(sha)
        os.chmod(path, 0o600)
        path.write_bytes(b"changed")
        return status

    monkeypatch.setattr(pipeline, "_record", record_then_damage)
    marker = Path(ctx.settings.data_dir) / "yara-started"
    assert process(ctx, fake_yara(f"spy:{marker}")) == "partial"
    assert not marker.exists()
    run = run_of(client, run_id)
    assert run["failure_reason"] == "sample_integrity"
    assert step_of(run, "strings")["status"] == "succeeded"
    assert step_of(run, "yara-x")["status"] == "skipped"
    assert "admission checks" in step_of(run, "yara-x")["message"]


