@pytest.mark.parametrize("damage", ["missing", "changed", "truncated"])
def test_worker_never_starts_yara_x_on_a_missing_or_changed_blob(
    client: TestClient, tmp_path: Path, damage: str
) -> None:
    version_id = imported_version(client, ELF_X86_64)
    run_id = start_run(client, version_id)["id"]
    ctx = ctx_of(client)
    sha = client.get(f"/api/v1/sample-versions/{version_id}").json()["sha256"]
    path = ctx.blobs.path(sha)
    os.chmod(path, 0o600)
    if damage == "missing":
        path.unlink()
    elif damage == "changed":
        path.write_bytes(b"\x7fELF" + bytes(100))
    else:
        path.write_bytes(path.read_bytes()[:-1])
    marker, strings_marker = tmp_path / "started", tmp_path / "strings-started"
    assert (
        process(
            ctx,
            fake_yara(f"spy:{marker}"),
            strings_command=fake_strings(f"spy:{strings_marker}"),
        )
        == "failed"
    )
    assert not marker.exists() and not strings_marker.exists()
    run = client.get(f"/api/v1/runs/{run_id}").json()
    assert run["failure_reason"] == "sample_integrity"
    assert "no analysis tool saw it" in run["failure_message"]
    for step in run["steps"]:
        assert step["status"] == "skipped" and step["tool_version"] is None
        assert "admission checks" in step["message"]


