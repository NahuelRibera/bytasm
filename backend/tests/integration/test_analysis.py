def fake_yara(behaviour: str) -> list[str]:
    return [sys.executable, "-I", str(FAKE_YARA), behaviour]


def fake_strings(behaviour: str) -> list[str]:
    return [sys.executable, "-I", str(FAKE_STRINGS), behaviour]


def step_of(run: dict[str, Any], tool: str) -> dict[str, Any]:
    step: dict[str, Any] = next(s for s in run["steps"] if s["tool"] == tool)
    return step


def deps_for(ctx: AppContext, command: list[str] | None = None, **changes: Any) -> ScanDeps:
    values: dict[str, Any] = {
        "sessions": ctx.sessions,
        "blobs": ctx.blobs,
        "outputs": ctx.outputs,
        "policy": ctx.policy,
        "limits": ctx.settings.limits,
        "tmp_dir": ctx.tmp_dir,
        "adapter_command": command or yara_adapter_command(),
    }
    values.update(changes)
    return ScanDeps(**values)


def process(ctx: AppContext, command: list[str] | None = None, **changes: Any) -> str | None:
    worker = Worker(deps_for(ctx, command, **changes), ctx.settings.data_dir, asyncio.Event())
    return asyncio.run(worker.process_next())


def write_rules(directory: Path, files: dict[str, str], version: str = "0.0.1") -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.glob("*.yar"):
        old.unlink()
    (directory / "ruleset.json").write_text(
        json.dumps({"name": "test-rules", "version": version}), encoding="utf-8"
    )
    for name, text in files.items():
        (directory / name).write_text(text, encoding="utf-8")
    return directory


