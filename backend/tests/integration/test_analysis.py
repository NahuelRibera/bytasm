def test_known_match_is_persisted_with_evidence_that_matches_the_file(client: TestClient) -> None:
    version_id = imported_version(client, ELF_X86_64)
    queued = start_run(client, version_id)
    assert queued["status"] == "queued"
    assert [(s["tool"], s["status"]) for s in queued["steps"]] == [
        ("strings", "queued"),
        ("yara-x", "queued"),
    ]
    assert queued["rule_set"]["label"] == "bytasm-rules@0.2.0"
    assert (
        queued["sample"]["sha256"]
        == client.get(f"/api/v1/sample-versions/{version_id}").json()["sha256"]
    )

    ctx = ctx_of(client)
    assert process(ctx) == "succeeded"
    run = client.get(f"/api/v1/runs/{queued['id']}").json()
    assert run["status"] == "succeeded"
    assert run["failure_reason"] is None and run["failure_message"] is None
    assert run["started_at"] and run["finished_at"]
    assert [s["status"] for s in run["steps"]] == ["succeeded", "succeeded"]
    assert run["counts"]["strings"] > 0
    step = step_of(run, "yara-x")
    assert step["status"] == "succeeded"
    assert step["tool"] == "yara-x" and step["tool_version"] == scan.yara_x_installed_version()
    assert step["raw_output_sha256"]

    findings = client.get(f"/api/v1/runs/{queued['id']}/findings").json()
    assert findings["notices"] == list(FINDING_NOTICES)
    assert [f["rule_id"] for f in findings["findings"]] == [
        "elf_dynamic_loader_path",
        "url_reference",
    ]
    finding = findings["findings"][1]
    assert finding["kind"] == "yara_match"
    assert finding["match_count"] == 1 and not finding["evidence_truncated"]
    [evidence] = finding["evidence"]
    data = ELF_X86_64.read_bytes()
    assert evidence["pattern_id"] == "$https"
    assert evidence["length"] == len(b"https://")
    offset = evidence["file_offset"]
    # The invariant from blueprint 9.1: the excerpt equals the file's bytes there.
    assert data[offset : offset + evidence["length"]] == b"https://"
    assert bytes.fromhex(evidence["excerpt_hex"]) == b"https://"
    assert evidence["excerpt_truncated"] is False
    # Pattern 0 is $http (no match), pattern 1 is $https.
    assert evidence["raw_json_pointer"] == "/scan/matching_rules/1/patterns/1/matches/0"
    # No verdict-like fields or wording in the machine-generated part.
    text = json.dumps(findings["findings"]).lower()
    for word in ("malicious", "severity", "score", "verdict", "safe"):
        assert word not in text


