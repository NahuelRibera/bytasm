# --- real processes: `bytasm serve` app + `bytasm worker` over HTTP ----------


def test_live_server_and_worker_process_complete_a_run(tmp_path: Path) -> None:
    import subprocess

    import httpx
    from api_support import import_headers, live_server

    with live_server(tmp_path) as (settings, _ctx):
        env = {
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
            "BYTASM_DATA_DIR": str(settings.data_dir),
            "BYTASM_PORT": str(settings.port),
        }
        worker = subprocess.Popen(
            [sys.executable, "-m", "bytasm", "worker"],
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
        )
        try:
            base = f"http://127.0.0.1:{settings.port}"
            headers = {"X-Bytasm-Request": "1"}
            with httpx.Client(base_url=base, headers=headers, timeout=30) as http:
                assert wait_until(
                    lambda: (
                        http.get("/api/v1/health").json()["worker_last_seen_seconds"] is not None
                    )
                )
                second = subprocess.run(
                    [sys.executable, "-m", "bytasm", "worker"],
                    env=env,
                    capture_output=True,
                    timeout=30,
                )
                assert second.returncode == 1
                assert b"already using this data directory" in second.stderr

                project = http.post("/api/v1/projects", json={"name": "Live"}).json()["id"]
                imported = http.post(
                    f"/api/v1/projects/{project}/imports",
                    content=ELF_X86_64.read_bytes(),
                    headers=import_headers(),
                )
                assert imported.status_code == 201, imported.text
                version_id = imported.json()["sample_version"]["id"]
                run_id = http.post(
                    f"/api/v1/sample-versions/{version_id}/runs", json=RUN_BODY
                ).json()["id"]
                assert wait_until(
                    lambda: http.get(f"/api/v1/runs/{run_id}").json()["status"] == "succeeded",
                    timeout=30,
                )
                findings = http.get(f"/api/v1/runs/{run_id}/findings").json()["findings"]
                assert [f["rule_id"] for f in findings] == [
                    "elf_dynamic_loader_path",
                    "url_reference",
                ]
        finally:
            worker.send_signal(signal.SIGTERM)
            _, stderr = worker.communicate(timeout=15)
        assert worker.returncode == 0, stderr.decode()
        # The worker never logs sample or matched bytes.
        assert b"https://" not in stderr and b"bytasm fixture" not in stderr
