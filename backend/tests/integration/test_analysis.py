def test_editing_rules_after_a_run_keeps_the_old_run_reproducible(tmp_path: Path) -> None:
    rules = write_rules(tmp_path / "rules", {"url_reference.yar": URL_RULE})
    with api_client(make_settings(tmp_path, rules_dir=rules)) as client:
        version_id = imported_version(client, ELF_X86_64)
        first = start_run(client, version_id)
        process(ctx_of(client))

        edited = URL_RULE.replace("https://", "bytasm fixture")
        write_rules(rules, {"url_reference.yar": edited}, version="0.0.2")
        second = start_run(client, version_id)
        process(ctx_of(client))

        assert first["rule_set"]["sha256"] != second["rule_set"]["sha256"]
        old = client.get(f"/api/v1/rule-sets/{first['rule_set']['id']}").json()
        assert old["current"] is False and old["version"] == "0.0.1"
        assert old["files"][0]["text"] == URL_RULE  # the exact text the first run used
        new = client.get(f"/api/v1/rule-sets/{second['rule_set']['id']}").json()
        assert new["current"] is True and new["files"][0]["text"] == edited

        def excerpt(run_id: str) -> bytes:
            finding = client.get(f"/api/v1/runs/{run_id}/findings").json()["findings"][0]
            return bytes.fromhex(finding["evidence"][0]["excerpt_hex"])

        assert excerpt(first["id"]) == b"https://"
        assert excerpt(second["id"]) == b"bytasm fixture"
        with ctx_of(client).sessions() as session:
            assert len(session.scalars(select(RuleSet)).all()) == 2


