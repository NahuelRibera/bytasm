# --- /proc/<pid>/environ of the parent (Q6) --------------------------------

_ENVIRON_PROBE = """
import subprocess, sys
from bytasm.runner.hardening import make_non_dumpable
if sys.argv[1] == "hardened":
    assert make_non_dumpable()
reader = (
    "import os\\n"
    "try:\\n"
    "    open(f'/proc/{os.getppid()}/environ', 'rb').read()\\n"
    "    print('READABLE')\\n"
    "except PermissionError:\\n"
    "    print('DENIED')\\n"
)
out = subprocess.run([sys.executable, "-I", "-c", reader], capture_output=True, text=True)
print(out.stdout.strip())
"""


@pytest.mark.skipif(not ON_LINUX, reason="/proc and PR_SET_DUMPABLE are Linux-only")
@pytest.mark.parametrize(("mode", "expected"), [("plain", "READABLE"), ("hardened", "DENIED")])
def test_non_dumpable_parent_hides_its_environment_from_children(mode: str, expected: str) -> None:
    result = subprocess.run(
        [sys.executable, "-c", _ENVIRON_PROBE, mode],
        capture_output=True,
        text=True,
        timeout=60,
        check=True,
    )
    assert result.stdout.strip() == expected


def test_result_path_swapped_for_a_fifo_is_refused_without_blocking(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Only a process that escaped the group kill could swap result.json after
    the lstat check; opening it must neither block nor read anything."""
    from bytasm.runner import supervisor

    regular = tmp_path / "regular"
    regular.write_bytes(b"{}")
    os.mkfifo(tmp_path / supervisor.RESULT_NAME)
    real_lstat = os.lstat
    # Make the pre-open check see a regular file, as if the swap came after it.
    monkeypatch.setattr(
        os,
        "lstat",
        lambda path: real_lstat(regular) if str(path).endswith("result.json") else real_lstat(path),
    )
    started = time.monotonic()
    assert supervisor._read_result(tmp_path, 1024) is None
    assert time.monotonic() - started < 2
