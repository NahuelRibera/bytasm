"""M2: the adapter runner (blueprint 9.1 "Subprocess runner", questions Q3-Q5).

Fake adapters (tests/fake_adapters/fake_adapter.py) misbehave on purpose. The
real LIEF adapter runs on committed fixtures and on generated bytes. Fixtures
are only read and parsed as data; nothing is executed.
"""

import asyncio
import json
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

import pytest
from conftest import ELF_AARCH64, PE_X86_64_EXE, sha256_of
from generated_inputs import truncated

from bytasm.adapters.result import AdapterResult
from bytasm.runner import workspace
from bytasm.runner.limits import ParserLimits
from bytasm.runner.supervisor import (
    CHILD_ENV,
    AdapterOutcome,
    metadata_adapter_command,
    run_adapter,
)

FAKE = Path(__file__).resolve().parents[1] / "fake_adapters" / "fake_adapter.py"
FAST = ParserLimits(timeout_seconds=2.0, kill_grace_seconds=0.5, pipe_close_seconds=1.0)
ON_LINUX = sys.platform == "linux"


def fake(behaviour: str) -> list[str]:
    return [sys.executable, "-I", str(FAKE), behaviour]


@pytest.fixture
def workdir(tmp_path: Path) -> Path:
    """A work directory holding a fixture as upload.bin and a valid template result."""
    directory = workspace.create_workdir(tmp_path / "runs")
    data = ELF_AARCH64.read_bytes()
    workspace.write_input(directory, data)
    real = asyncio.run(run_adapter(metadata_adapter_command(), directory, sha256_of(data)))
    assert real.status == "succeeded" and real.result_bytes is not None
    (directory / "result.json").unlink()
    (directory / "template.json").write_bytes(real.result_bytes)
    return directory


def run_fake(
    behaviour: str, workdir: Path, limits: ParserLimits = FAST, sha: str | None = None
) -> AdapterOutcome[AdapterResult]:
    expected = sha or sha256_of(workspace.input_path(workdir).read_bytes())
    return asyncio.run(run_adapter(fake(behaviour), workdir, expected, limits))


def process_gone(pid: int, timeout: float = 5.0) -> bool:
    """True once `pid` no longer exists (or is only an unreaped zombie)."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return True
        except PermissionError:
            return True
        stat_path = Path(f"/proc/{pid}/stat")
        if ON_LINUX and stat_path.exists():
            state = stat_path.read_text().rsplit(")", 1)[1].split()[0]
            if state == "Z":
                return True
        time.sleep(0.05)
    return False


def recorded_pids(workdir: Path, timeout: float = 3.0) -> list[int]:
    path = workdir / "pids.txt"
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline and not path.exists():
        time.sleep(0.02)
    return [int(line) for line in path.read_text().split()]


# --- the real adapter -------------------------------------------------------


@pytest.mark.parametrize("fixture", [ELF_AARCH64, PE_X86_64_EXE], ids=lambda p: p.name)
def test_real_adapter_parses_fixture_in_child(tmp_path: Path, fixture: Path) -> None:
    directory = workspace.create_workdir(tmp_path)
    data = fixture.read_bytes()
    workspace.write_input(directory, data)
    outcome = asyncio.run(run_adapter(metadata_adapter_command(), directory, sha256_of(data)))
    assert outcome.status == "succeeded", outcome
    assert outcome.exit_code == 0
    assert outcome.result is not None
    assert outcome.result.input.sha256 == sha256_of(data)
    assert outcome.result.input.size_bytes == len(data)
    assert outcome.result.tool == "lief"
    assert outcome.stdout == "" and outcome.stderr == ""
    limits = outcome.result.resource_limits
    assert limits.cpu_seconds == 25
    assert limits.file_size_bytes == 32 * 1024 * 1024
    assert limits.core_bytes == 0
    if ON_LINUX:
        assert limits.address_space_bytes == 1024**3
    elif sys.platform == "darwin":
        # macOS refuses RLIMIT_AS below the address space already reserved.
        assert limits.address_space_bytes is None


def test_real_adapter_rejects_malformed_bytes_with_reason_code(tmp_path: Path) -> None:
    directory = workspace.create_workdir(tmp_path)
    data = truncated(ELF_AARCH64.read_bytes(), 40)
    workspace.write_input(directory, data)
    outcome = asyncio.run(run_adapter(metadata_adapter_command(), directory, sha256_of(data)))
    assert (outcome.status, outcome.reason, outcome.exit_code) == (
        "rejected",
        "malformed_input",
        2,
    )
    assert outcome.result is None


def test_real_adapter_refuses_bytes_that_differ_from_the_admitted_hash(tmp_path: Path) -> None:
    """The child re-hashes its input, so it never parses anything but admitted bytes."""
    directory = workspace.create_workdir(tmp_path)
    workspace.write_input(directory, ELF_AARCH64.read_bytes())
    outcome = asyncio.run(run_adapter(metadata_adapter_command(), directory, "a" * 64))
    assert (outcome.status, outcome.reason, outcome.exit_code) == ("failed", "nonzero_exit", 4)
    assert not (directory / "result.json").exists()


def test_child_applies_limits_before_lief_is_imported(tmp_path: Path) -> None:
    script = (
        "import sys\n"
        "import bytasm.adapters.metadata_lief as adapter\n"
        "from bytasm.runner import child\n"
        "assert 'lief' not in sys.modules, 'importing the adapter loaded LIEF'\n"
        "real = child.apply_resource_limits\n"
        "def spy(args):\n"
        "    print('LIEF_LOADED_AT_LIMITS=' + str('lief' in sys.modules))\n"
        "    return real(args)\n"
        "child.apply_resource_limits = spy\n"
        "code = adapter.main(sys.argv[1:])\n"
        "print('LIEF_LOADED_AFTER=' + str('lief' in sys.modules))\n"
        "print('EXIT=' + str(code))\n"
    )
    directory = workspace.create_workdir(tmp_path)
    data = ELF_AARCH64.read_bytes()
    workspace.write_input(directory, data)
    result = subprocess.run(
        [sys.executable, "-I", "-c", script, "--input", "upload.bin", "--out", "result.json"]
        + ["--expected-sha256", sha256_of(data), "--max-input-bytes", "67108864"]
        + ["--rlimit-as", str(1024**3), "--rlimit-cpu", "25", "--rlimit-fsize", "33554432"],
        cwd=directory,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    assert "LIEF_LOADED_AT_LIMITS=False" in result.stdout, result.stderr
    assert "LIEF_LOADED_AFTER=True" in result.stdout
    assert "EXIT=0" in result.stdout


