# --- timeouts, process groups, and cleanup (Q3, Q4) ------------------------


def test_hanging_child_is_killed_at_the_timeout(workdir: Path) -> None:
    started = time.monotonic()
    outcome = run_fake("hang", workdir, ParserLimits(timeout_seconds=1, kill_grace_seconds=0.5))
    elapsed = time.monotonic() - started
    assert (outcome.status, outcome.reason) == ("timed_out", "timeout")
    assert outcome.exit_code == -signal.SIGTERM
    assert elapsed < 4
    assert all(process_gone(pid) for pid in recorded_pids(workdir))


def test_child_ignoring_sigterm_gets_sigkill_after_grace(workdir: Path) -> None:
    limits = ParserLimits(timeout_seconds=1, kill_grace_seconds=0.5)
    outcome = run_fake("ignore_sigterm", workdir, limits)
    assert outcome.status == "timed_out"
    assert outcome.exit_code == -signal.SIGKILL
    assert all(process_gone(pid) for pid in recorded_pids(workdir))


def test_grandchild_left_in_the_group_is_killed_and_run_fails(workdir: Path) -> None:
    outcome = run_fake("fork_orphan", workdir, ParserLimits(timeout_seconds=5))
    assert (outcome.status, outcome.reason) == ("failed", "orphan_processes")
    assert outcome.result is None
    (grandchild,) = recorded_pids(workdir)
    assert process_gone(grandchild)


def test_process_that_leaves_the_group_is_detected_but_not_killed(workdir: Path) -> None:
    """Q4, recorded limitation: setsid() escapes the group kill.

    The escapee keeps stdout open, so the run fails (`output_not_closed`) and
    its result is not used. The runner cannot kill it; the test does.
    """
    limits = ParserLimits(timeout_seconds=5, pipe_close_seconds=0.5)
    outcome = run_fake("setsid_escape", workdir, limits)
    (escapee,) = recorded_pids(workdir)
    try:
        assert (outcome.status, outcome.reason) == ("failed", "output_not_closed")
        assert outcome.result is None
        assert not process_gone(escapee, timeout=0.2), "expected the escapee to survive"
    finally:
        os.kill(escapee, signal.SIGKILL)
    assert process_gone(escapee)


def test_cancelling_the_run_kills_the_child(workdir: Path) -> None:
    """Q3: cancellation of the awaiting task still kills and reaps the group."""

    async def scenario() -> None:
        sha = sha256_of(workspace.input_path(workdir).read_bytes())
        limits = ParserLimits(timeout_seconds=30)
        task = asyncio.create_task(run_adapter(fake("hang"), workdir, sha, limits))
        await asyncio.sleep(1.0)
        task.cancel()
        with pytest.raises(asyncio.CancelledError):
            await task

    asyncio.run(scenario())
    assert all(process_gone(pid) for pid in recorded_pids(workdir))


def test_cancelling_during_the_kill_grace_period_still_kills(workdir: Path) -> None:
    """Q3: cancellation injected inside the SIGTERM -> SIGKILL path."""

    async def scenario() -> None:
        sha = sha256_of(workspace.input_path(workdir).read_bytes())
        limits = ParserLimits(timeout_seconds=0.5, kill_grace_seconds=5)
        task = asyncio.create_task(run_adapter(fake("ignore_sigterm"), workdir, sha, limits))
        await asyncio.sleep(1.5)  # timeout passed; now waiting out the grace period
        task.cancel()
        with pytest.raises(asyncio.CancelledError):
            await task

    asyncio.run(scenario())
    assert all(process_gone(pid) for pid in recorded_pids(workdir))


